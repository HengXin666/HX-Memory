// src/capture/output-signal.ts — **本轮产出**的信号判定 (判据的输入侧修正)。
//
// 为什么需要它 (2026-09-18 独立盲审 + 我方复现的结构性缺陷):
//   丢弃判据此前只吃 `input.text` (**用户的措辞**), assistant 的回答完全不参与 ——
//   实测 "next" 配一段含根因/文件路径/端口的回答, 与配空回答得到**逐字相同**的结果
//   (`no-signal:context`)。于是判据判的是"用户那句话的措辞", 而不是"这一轮产出了什么"。
//   后果: 真库 229 轮里 202 轮被丢 (88.2%), 其中被判据丢掉的 131 轮里 assistant 输出
//   41.1 万字符 —— 丢弃量是保留量的 3.6 倍。这些不是"低价值轮次", 是"判据看不见的轮次"。
//
// 边界 (这是**廉价规则**, 不是价值判断):
//   · 它只回答"这一轮的产出里有没有可沉淀的实质内容", 不做"值不值得记"的判断
//     (那是结构化器与人工闸门的事);
//   · 纯确定性, 0 LLM 成本, 可测试 —— 与 heuristicStructurer 同一价值观;
//   · 宁可放过 (进结构化器后仍可能被结论闸门拦下), 不轻易拦死 —— 本模块只做**入口放宽**。
//
// 与"捡回噪声"的关系: 放宽入口必然引入噪声风险, 因此配套三道闸在 pipeline/engine 层:
//   (a) 本模块先筛 (把明显无产出的轮次挡在外面);
//   (b) 结论闸门要求结构化器读出 conclusion, 读不出仍丢;
//   (c) 负例回归测试固化"该丢的仍丢"(tests/s1/capture-output-signal.test.ts)。

/** 产出信号类别 (命中**至少两类**才算"有实质产出", 避免单一特征误判)。 */
const OUTPUT_SIGNALS: ReadonlyArray<RegExp> = [
  // 1) 具体标识符: 文件路径 / 行号 / 端口 / hash / 文件名
  //
  // ⚠ 2026-09-18 自查修复: 原写法 `(?:[\w./-]+\.(?:ts|…))` 是**嵌套量词**, 属 ReDoS 形态 ——
  // 实测在 10 万字符输入上耗时 **2289ms**, 而本函数在**捕获路径上每轮同步执行**。
  // 真实数据里 assistant 回答最长 59037 字符 (虽因"提前命中返回"未触发, 但属条件性风险)。
  // 改为**有界量词** (实测: 关键在"无界量词"而非嵌套 ——
  // 原版 2293ms / 有 `*` 的版本 1849ms / 只找扩展名 0ms / 前置词限定 {1,64} **14ms**)。
  // 文件名有实际长度上限, 因此限定 {1,64} 不损失任何真实匹配能力。
  /[\w-]{1,64}\.(?:ts|tsx|js|mjs|cjs|py|go|rs|json|md|yaml|yml|sql|toml)\b(?::\d+)?/i,
  /\b(?:port|端口)\s*[:=]?\s*\d{2,5}\b/i,
  /\b[0-9a-f]{7,40}\b/i,
  // 2) 根因 / 结论语
  /根因|原因是|是因为|问题出在|本质是|结论[:：]|修复方式|解决方案|the (?:root )?cause|because/i,
  // 3) 错误码 / 错误形态
  /\b(?:E[A-Z]{2,}|ERR_[A-Z_]+)\b|\b(?:4\d{2}|5\d{2})\b|错误[:：]|报错|失败原因/i,
  // 4) 代码块 / 命令
  /```|^\s*(?:\$|npm|pnpm|node|git|curl|docker|kubectl)\s/m,
  // 5) 决策 / 定论语
  /已(?:修复|完成|落地|改成|改为|统一)|决定|最终(?:方案|选择)|不再|禁止|必须/i,
];

/**
 * 无信息量的**用户指令** (继续/确认/动作词)。
 *
 * 为什么要单独判: 放开"按产出放行"后, "继续啊"/"next" 这类指令也会被放行 ——
 * 它们配一段长回答确实能命中产出信号, 但**用户并没有提出任何信息需求**, 落盘的会是
 * "上一轮工作的汇报"而不是"用户要记住的东西"。实测该放行让 "继续啊" 进了候选 (精度检验捕获)。
 *
 * 判据: 整句只有指令词 (可带标点/语气词), 不含任何具体对象 (文件名/名词短语)。
 * 保守取"整句匹配"而不是"包含" —— "继续修那个 500 错误" 含具体对象, 不该被拦。
 */
const BARE_COMMAND_RE =
  /^\s*(?:next|yes|no|ok|okay|go|run|continue|fix|fix it|all|do it|继续[啊吧]?|好[的吧]?|可以|行|嗯|对|是的|来|开始|go on|next step)[\s。.!！?？~～]*$/i;

/**
 * 该回答是否含"实质产出"。
 *
 * question 参数的存在只为**提高门槛**(见下), 不是"纯指令一律拒绝":
 * 纯指令 ("继续啊"/"next") 本身没有信息需求, 但它的**回答可能有实质产出** ——
 * 该不该记应当由"这一轮产出了什么"决定, 而不是由"用户那句话长什么样"决定
 * (那正是本模块要修正的原缺陷)。因此纯指令只提高信号门槛, 不直接拒绝。
 */
export function hasSubstantiveOutput(answer: string | undefined, question?: string): boolean {
  const text = (answer ?? "").trim();
  // 长度下限: 实测被丢弃轮次的 assistant 平均 3,384 字符, 而"确实该丢"的样本 assistant 为空;
  // 取 300 作为下限 —— 低于它的回答几乎不可能承载"根因 + 具体标识符"这类可沉淀内容。
  if (text.length < MIN_OUTPUT_LENGTH) return false;
  // 纯指令要求**更高的信号门槛** (3 类而非 2 类)。
  // 为什么不是直接拒绝: "继续啊" 之后的回答常常正是整轮工作的总结 (根因/路径/结论齐全),
  // 那是真产出; 但同样一段回答若只沾边两类信号, 更可能是"随口回了几句"。
  // 提高门槛比一刀切更贴合"按产出判定"的本意 —— 实测该阈值下人工噪声清单命中 0。
  const bare = question !== undefined && BARE_COMMAND_RE.test(question);
  const need = bare ? MIN_SIGNAL_KINDS + 1 : MIN_SIGNAL_KINDS;
  let kinds = 0;
  for (const re of OUTPUT_SIGNALS) {
    if (re.test(text)) kinds++;
    if (kinds >= need) return true;
  }
  return false;
}

/**
 * 长度下限 (300 字符)。
 *
 * 为什么是这个量级并附实测: 盲审给出的可分性证据显示, 一条朴素的
 * "answer >= 800 字符 且命中 {根因|错误|路径}" 规则在 27 条已存轮次上命中 100%、
 * 在 103 条被丢弃轮次上命中 74%。本模块进一步放宽到 300 并要求**两类**信号,
 * 目的是把"漏掉"换成"多送进结构化器"—— 后续闸门仍会拦, 而漏掉是不可逆的。
 */
export const MIN_OUTPUT_LENGTH = 300;

/** 至少命中几类信号 (单一特征容易误判: 长报告里出现一个 "5xx" 不足以说明有产出)。 */
export const MIN_SIGNAL_KINDS = 2;
