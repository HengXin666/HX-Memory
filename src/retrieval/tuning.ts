// retrieval/tuning.ts — 检索期的**标定常量** (全部是测出来的, 不是拍的)。
//
// 为什么单独一个文件: 这些数字的**变化原因**与检索算法完全不同 —— 算法随设计变,
// 常量随评测数据变。混在一起时, 改一个配额就要在 400 行的检索器里翻找, 而且很容易
// 只改了这里、忘了那边 (实测踩到过: 实体通道的四个参数只存在于检索器构造参数里,
// 而生产路径全部经 openMemoryStack 组装, 不透传 = 这些设置永远不生效, 而扫描多组配置
// 会得到完全相同的读数, 看起来像"参数没影响")。
//
// 每个常量都注明依据与**代价**, 因为它们的取值都来自"两头读数方向相反"的取舍。
import type { Channel } from "../kernel/ports.ts";

/**
 * 实体通道进榜上限 (tier2 模式下生效)。
 *
 * 依据 (80 条语料 / 171 主 case + 104 entity_only case; 确定性纯词面臂):
 *   上限 4 → entity_only H@10 0.144; 8 → 0.250; **16 → 0.2596 且此后不再增长** (候选池有界);
 *   主 case 在**所有**上限下都与关闭该通道逐位相同 (H@1 0.807 / H@10 0.9123) ——
 *   因为 tier2 只补位、不参与打分竞争。取 16 是因为收益在这里封顶, 不是因为"越大越多"。
 * 对照: 若把该通道放进主排序 (`entityMode: "main"`), 主 case H@1 掉到 0.503 —— 见下。
 */
export const DEFAULT_ENTITY_MAX_IDS = 16;

/** 共享实体门槛: 1 = 任意共享。实测 2 在 entity_only 上没有任何提升 (桥会因为强连接太少而断掉)。 */
export const DEFAULT_ENTITY_MIN_SHARED = 1;

/**
 * 实体候选的默认出口。
 *
 * "main" (与词面竞争主排序) 实测**两头都输**: entity_only H@10 0.106 (远低于 tier2 的 0.260),
 * 主 case H@1 0.807 → 0.5029、H@10 0.9123 → 0.8304。原因是实体候选与图候选同性质 ——
 * 是"主题邻居"而不是答案 (图候选的 gold 精确率实测只有 8.5%)。
 * 因此默认走独立配额的尾巴, 与图通道当初的修法一致 (R@1 0.684 vs 0.630 → 分层后两头都保住)。
 */
export const DEFAULT_ENTITY_MODE: "main" | "tier2" = "tier2";

/**
 * tier2 模式下实体候选的配额。
 *
 * 它与 graphTierQuota (3) 分开而不是共用一份: 两个通道的候选质量不同,
 * 合成一份配额会让一个通道的长列表把另一个挤掉 (assemble.ts 里按通道分别计数)。
 * 取值 8 是实测的**饱和点**: entity_only H@10 在配额 3 时 0.154、8 时 0.250、20 时仍是 0.250。
 */
export const DEFAULT_ENTITY_QUOTA = 8;

/**
 * 词面通道的默认权重 (标定见 docs/memory-benchmark-report.md: 词面主导 + 语义补召回)。
 *
 * ⚠ 2026-09-18: **2 → 3 → 8** (两次标定)。
 *
 * ## ⚠⚠ 这一项**没有统计支持** (2026-09-18 自查, 必读)
 *
 * 用项目自带的配对检验 (`bench/lib/eval_kit.py` 的 `paired_bootstrap` / `mcnemar`) 复核:
 *
 * | 改动 | R@10 增益 | paired_bootstrap p | McNemar (改对/改错) |
 * | --- | --- | --- | --- |
 * | 2 → 3 | +0.026 | **0.72** | **1 / 0** |
 * | **3 → 8** | +0.026 | **0.72** | **1 / 0** |
 *
 * **即: 权重 8 相对 2 或 3 的差异只有 1 个 case** (在 k=20 下复测同样如此)。
 * 检测 +0.026 量级的改进需 **n≈2903**, 而当前基准只有 **38** 条样本 —— **功效严重不足**。
 *
 * **为什么仍然取 8**: ①方向一致 (四个分组全非负, 多轮独立测量读数不低于权重 2);
 * ②回退同样**没有统计依据** —— 用无依据的读数否定另一个无依据的读数没有意义;
 * ③真正的处置是**扩大基准样本**, 而不是在 38 条上反复摇摆。
 *
 * **不要**把这一项当作"已证实的标定"引用。它测得的差异**无法与随机波动区分**。
 *
 * ## 扩大样本后的最终判定 (2026-09-18, n=71)
 *
 * 把基准窗口从 30 分钟放宽到 120 分钟使样本 38 → **71** 后复测:
 *
 * | 对比 | R@10 delta | paired_bootstrap p | McNemar | 判定 |
 * | --- | --- | --- | --- | --- |
 * | **RRF k 60→20** | **+0.099** | **0.0172** | 8/1 (p=0.0391) | **显著** |
 * | 权重 2→8 (k=60 下) | −0.056 | 0.1254 | 5/1 | 不显著 |
 * | **权重 2→8 (k=20 下)** | **0.000** | **1.0000** | 1/1 | **完全无差异** |
 *
 * **即: 在 k=20 下, 权重 8 与权重 2 的表现完全相同** (delta = 0.000) ——
 * 这一项调整**确实没有带来任何改变**。保留 8 仅因它无害且方向直观,
 * 真正的改进来自 RRF k 值 (那项在新样本下依然显著)。
 *
 * **第二次 (3 → 8) 的触发条件是 RRF k 值同时从 60 改到 20** —— 参数之间存在交互,
 * 单独调权重时 3 是最优点, 而 k 值改善后最优点**右移**:
 *
 * | bm25 权重 | 旧 k=60 下 R@1/R@10 | **新 k=20 下 R@1/R@10** |
 * | --- | --- | --- |
 * | 3 | 0.132/0.526 | 0.132/0.684 |
 * | **8 (新默认)** | 0.105/0.579 | **0.158/0.711** |
 * | 12 | 0.053/0.579 | 0.184/0.711 |
 *
 * **即: 旧 k 下权重 8 会伤 R@1 (0.132→0.105); 新 k 下权重 8 反而提 R@1 (0.132→0.158)。**
 * 取 8 而不是 12~16 (那档 R@1 能到 0.184): 8 已是**平台期起点** (8/10 同值), 取平台起点更稳。
 * 弃权行为在所有权重下保持 3/4 不变; 四个分组方向全非负; 1010 项契约全绿。
 *
 * 第一次标定 (2 → 3) 的依据 (真实对话基准上的分组稳健性检验):
 *
 * | 分组 | n | w=2 R@1/R@10 | w=3 R@1/R@10 | 变化 |
 * | --- | --- | --- | --- | --- |
 * | 全部 | 38 | 0.105/0.500 | 0.132/0.526 | +0.026/+0.026 |
 * | 短查询 (<80 字符) | 19 | 0.105/0.579 | 0.158/0.579 | +0.053/0 |
 * | 长查询 (>=80 字符) | 19 | 0.105/0.421 | 0.105/0.474 | 0/+0.053 |
 * | 单 gold | 27 | 0.074/0.519 | 0.111/0.519 | +0.037/0 |
 *
 * **四个分组方向全部非负** ⇒ 不是过拟合到某一类查询; 且分工清晰:
 * 短查询靠它提**首位命中** (R@1), 长查询靠它把中位条目**捞回前 10** (R@10)。
 * 弃权行为不受影响 (库外问题在两个权重下都被正确弃权, 已实测)。
 *
 * 为什么不是更高的 5~8 (那档 R@10 能到 0.579, 更诱人): 它以**牺牲 R@1 与 R@3** 为代价
 * (R@1 0.132→0.105, R@3 0.342→0.316)。注入场景下模型最先读到的几条更重要 ⇒ 取 3。
 */
export const DEFAULT_BM25_WEIGHT = 8;

/**
 * 候选资格闸门的覆盖率下限 (0..1)。
 *
 * **⚠ 2026-09-18 实测: 曾试调 0.5 → 0.1, 已回退。** 记录在此以免重复尝试。
 *
 * 基准上它**确实**让 R@10 从 0.526 升到 0.553 (噪声代价也可忽略: 零覆盖命中 10.0%→9.5%,
 * 平均覆盖率不变), 但**破坏了 6 个既有测试**:
 *
 *   · "覆盖率过滤: 只共享一个 bigram 的噪声候选被丢弃" (该测试**就是为 0.5 门槛写的**);
 *   · 实体反查通道 5 项 (放宽门槛改变了候选集, 连带影响该通道的前提)。
 *
 * **判断**: 一个只提升 2.7pt 且连带破坏两个契约测试的调参, **不值得**。
 * R@10 的真实提升应当来自**更好的候选质量** (真语义嵌入器), 而不是放宽准入。
 *
 * 下表是当时的实测数据 (仅供未来参考; 若要重试, 必须同时修好那 6 个测试的语义):
 *
 * 原记录: 2026-09-18 曾从 0.5 试调到 0.1 —— 依据是真实对话基准上的实测 (含噪声代价测量):
 *
 * | coverageFloor | R@1 | R@10 | 平均词面覆盖率 | 零覆盖命中占比 |
 * | --- | --- | --- | --- | --- |
 * | 0.5 (原默认) | 0.132 | 0.526 | 0.227 | 10.0% |
 * | 0.15 | 0.132 | 0.526 | — | — |
 * | **0.1 (新默认)** | 0.132 | **0.553** | **0.227** | **9.5%** |
 * | 0 (完全绕过闸门) | 0.132 | 0.553 | 0.226 | 9.5% |
 *
 * **关键**: R@10 +2.7pt **几乎零噪声代价** (平均覆盖率不动, 零覆盖命中反而略降)。
 * 即那些被放行的候选**本来就有词面依据**, 只是此前被这道门槛误挡。
 *
 * 取 0.1 而不是 0: 0 会让 `qualifiesCandidate` 的第一道判断**恒真** (完全绕过闸门),
 * 而 0.1 仍要求"命中 >=2 个词 且 覆盖率 >=0.1", 闸门语义保留。
 */
export const DEFAULT_COVERAGE_FLOOR = 0.5;

/**
 * RRF 的 k 值 (默认 20, 原为 60)。
 *
 * ⚠ 2026-09-18 从 60 调到 20 —— 这是本会话**单次幅度最大**的改进, 依据是真实对话基准:
 *
 * | rrfK | R@1 | R@3 | R@10 |
 * | --- | --- | --- | --- |
 * | **60 (原默认)** | 0.132 | 0.342 | 0.526 |
 * | **20 (新默认)** | 0.132 | **0.421** | **0.684** |
 * | 1 (最激进的点) | 0.368 | 0.553 | 0.684 |
 *
 * **为什么 k=20 而不是更激进的 1~10** (那档 R@1 能到 0.368, 更诱人):
 * k <= 10 时**库外问题不再被正确弃权** (实测: 库外问题从 hits=0 变成 hits=5) ——
 * 即用"首位精度"换掉了"该说不知道的时候说不知道"。k=20 是**唯一同时满足**
 * "R@10 提升 + 弃权行为不变"的点 (库外正确弃权 3/4, 与 k=60 相同)。
 *
 * **机制**: \`rrfFuse\` 的分数是 \`Σ weight/(k+rank)\`。k=60 时相邻位次的原始分差仅 **1.8%**
 * (rank=1: 0.0164 vs rank=2: 0.0161), 实测**22% 的相邻位次相对分差 <1%**、70% <5% ——
 * 排序分辨力被压平。k 越小, 位次差异被放大得越明显 (k=1 时中位分差 11.7%)。
 *
 * **四个分组 (短/长查询、单/多 gold) 方向全部非负**, 且**不破坏任何契约测试** (1010 项全绿)。
 */
export const DEFAULT_RRF_K = 20;

/** 默认通道权重表 (生产组装与评测变体共用同一份, 避免"评测与线上不是同一套配置")。 */
export const DEFAULT_CHANNEL_WEIGHTS: Partial<Record<Channel, number>> = {
  bm25: DEFAULT_BM25_WEIGHT,
};
