// kernel/function-words.ts — 查询侧的虚词判据 (只服务覆盖率, 不碰分词与索引)。
//
// 为什么需要它 (2026-09-17 实测, 本机真实库 109 条):
//   覆盖率 = "命中的查询词 / 查询词总数", 而查询词里混着大量虚词与单字碎片。
//   实测 "如何用 Rust 写一个 WebSocket 服务器" 在一条**完全无关**的 HX-Sagasu 工作日志上
//   得到 cov=0.63 —— 命中的是 用/写/一个/服务 四个词, 其中三个是虚词或碎片。
//   后果不是"排序差一点", 而是**弃权永不发生**: 任何查询都能在库里找到"高覆盖"的条目,
//   No relevant memory found 这条分支形同不存在, 模型拿到 10 条看似相关的记忆全是噪声。
//
// 为什么是词表而不是 IDF: 虚词是**封闭类** (语法词, 数量固定、跨语料稳定), 而内容词的稀有度
//   依赖语料规模与主题, 会随库增长而漂移。给封闭类做减法不会随话题失效 —— 这与
//   "给开放类 (话题词) 打补丁" 是两种性质不同的做法 (后者被实测否决过: 词表永远追不上话题)。
//
// 边界 (三条, 都由 tests/s1/function-words.test.ts 钉住):
//   1. 只影响**查询侧的覆盖率权重** (queryTerms().weighted), 不影响 terms (bigram 流),
//      不影响 BM25 的原文查询, 也不影响索引 —— 索引仍收全部词。
//   2. 因此"索引与查询必须共用同一分词函数"这条不变量不受影响: 分词仍在 kernel/cjk。
//   3. 过滤后若一个词都不剩, 调用方必须**退回未过滤的词表** —— 单字查询 ("卡") 不能因此失效。
//
// 放在 kernel 层: 纯函数、零依赖、无 IO, 可被检索层与任何未来的消费方共用。

/**
 * 虚词表 (封闭类: 代词 / 疑问词 / 量词 / 助词 / 连词 / 介词 / 副词 / 常见动词短语)。
 *
 * 收录判据只有一条: **它在语料里出现不构成"这条记忆与查询相关"的证据**。
 * 因此"服务"/"提交"这类内容词一律不收 (它们确实有区分度), 而"一个"/"什么"这类收。
 */
const FUNCTION_WORDS: ReadonlySet<string> = new Set([
  // 代词
  "我", "你", "他", "她", "它", "我们", "你们", "他们", "我的", "你的", "他的", "自己", "大家",
  // 疑问 / 指示
  "什么", "怎么", "怎样", "如何", "为什么", "哪个", "哪些", "哪里", "多少", "这个", "那个",
  "这些", "那些", "这样", "那样", "这种", "那种", "一下", "一些",
  // 量词 / 助词 / 语气
  "一个", "一种", "的话", "了吗", "而已", "罢了",
  // 连词 / 介词
  "因为", "所以", "但是", "不过", "而且", "或者", "还是", "如果", "虽然", "然后", "以及",
  "关于", "对于", "由于", "为了", "通过", "根据", "按照", "除了", "包括",
  // 副词 / 助动词
  "可以", "需要", "应该", "必须", "已经", "正在", "就是", "不是", "没有", "可能", "也许",
  "非常", "比较", "有点", "一定", "其实", "当然", "一直", "总是", "经常",
  // 时间 / 处所 (在提问里几乎总是"什么时候/在哪里"的框架, 不是内容)
  "现在", "目前", "之前", "之后", "以后", "以前", "时候", "时间", "地方", "这里", "那里",
  // 常见提问框架动词
  "看看", "看下", "帮我", "请问", "麻烦", "谢谢", "知道", "觉得", "认为", "想要", "希望",
]);

/** 单个 CJK 字符 (含假名/谚文): 中文里几乎总是更长词的碎片 (服务器→器, 依赖数组→组)。 */
const SINGLE_CJK = /^[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uac00-\ud7af]$/;

/**
 * true = 这个词不参与覆盖率计算。
 *
 * 两类: ①封闭类虚词 (查表); ②单字碎片 (单个 CJK 字符或单个拉丁字母)。
 * 单字判据刻意只覆盖"一个字"的形状: "io" / "2fa" 这类短标识符不在此列 (长度 >= 2)。
 */
export function isFunctionWord(term: string): boolean {
  if (!term) return true;
  if (FUNCTION_WORDS.has(term)) return true;
  return SINGLE_CJK.test(term);
}

/**
 * 从一组查询词里挑出**有区分度**的那些 (用于覆盖率)。
 *
 * 返回空数组时调用方必须退回原词表: 单字查询 ("卡" / "网") 过滤后为空,
 * 此时"没有区分度的词"与"没有词"是两件事, 不能等同处理。
 */
export function discriminativeTerms(terms: readonly string[]): string[] {
  return terms.filter((t) => !isFunctionWord(t));
}
