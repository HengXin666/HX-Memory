// tests/s1/tuning-constants.test.ts — 标定常量必须有测试钉住它们的值。
//
// 为什么需要它 (2026-09-18 变异测试发现): 把 `DEFAULT_RRF_K` 从 20 改成 999,
// **1042 项测试全部通过**; `DEFAULT_BM25_WEIGHT` 从 8 改成 1 同样全过。
//
// 即: 这两个检索核心常量**没有任何测试保护** —— 而它们正是本会话反复标定的对象
// (RRF k 60→20 是本会话唯一经统计验证的改进: R@10 0.465 → 0.563)。
//
// **为什么既有测试测不出**: RRF 的 k 参数只改变**分数大小** (`1/(k+rank)`),
// 在小语料下**不改变排序顺序** —— 实测 rrfK=20/60/999 三档下,
// 分数是 0.0337 / 0.0116 / 0.0007, 而顺序都是 e0,e1,e2,e3,e4 完全一致。
// 所以断言"顺序"的测试天然覆盖不到它; 只有**专门断言常量值**才能拦住误改。
//
// 本文件的目的**不是**验证公式正确 (那由检索测试覆盖), 而是:
// **让"有人手滑改了标定值"这件事立刻变红**, 并在注释里说明它为什么是这个值。
import { describe, expect, it } from "vitest";
import {
  DEFAULT_BM25_WEIGHT,
  DEFAULT_COVERAGE_FLOOR,
  DEFAULT_RRF_K,
} from "../../src/retrieval/tuning.ts";

describe("标定常量 (改动必须是有意的)", () => {
  it("**DEFAULT_RRF_K = 20** (从 60 调下来, 有统计依据)", () => {
    // 为什么是 20: 60 → 20 使 R@10 从 0.465 升到 0.563; 配对 McNemar p=0.0391 (8 改 / 1 退),
    // paired_bootstrap p=0.0172, 符号翻转置换 p=0.0197; 且**按 gold 长度/查询长度/项目分层后
    // 各层非负** —— 是本会话唯一经完整统计验证的改动 (详见 tuning.ts 的注释)。
    expect(DEFAULT_RRF_K).toBe(20);
  });

  it("**DEFAULT_BM25_WEIGHT = 8** (统计不显著, 但已保留)", () => {
    // 为什么是 8: 2→3→8 的过程中 R@10 有提升, 但事后检验**未达显著**;
    // 项目选择保留而非回退 (注释里记了理由)。重要的是: 它不该被**无意**改动。
    expect(DEFAULT_BM25_WEIGHT).toBe(8);
  });

  it("**DEFAULT_COVERAGE_FLOOR = 0.5** (曾试过 0.1, 因破坏契约而回退)", () => {
    // 为什么回到 0.5: 0.1 让 R@10 升了 2.7pt, 但**破坏了 6 项契约测试**
    // (一个为 0.5 阈值写的 + 5 个实体通道的) ⇒ 回退。
    expect(DEFAULT_COVERAGE_FLOOR).toBe(0.5);
  });
});
