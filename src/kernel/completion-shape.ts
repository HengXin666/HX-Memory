// kernel/completion-shape.ts — 「这条记忆是不是一句**尚未完成的祈使/待办**」的单一判据。
//
// ## 为什么需要它 (2026-10-06 用户实测指控)
//
// 用户原话: 「你让别人已经完成的事情, 又以为他又自己又没有做… 你为什么要设计成一些事情
// 它是经验来的, 你又把它设计成是 1 个遗留问题, 导致 ai 又以为这是 1 个新问题」。
//
// 取证 (真库 1187 条 active, 2026-10-06):
//   · 含祈使/未完成语气且**无完成标记**的条目 **577 条**;
//   · 被**实际注入过**的「未完成语气」条目 44 条, 累计注入 **171 次**。
// 最典型的一条: `decision/HX-Jungle`「现在有一个非常严重的bug! gh-pool … 2FA 授权这个步骤
// 他那个队列并不会帮我们执行」 2026-09-28 存, 到 10-06 被注入 8 次, 而那个 bug 早已修完
// (任务台账 T20 有闭环证据)。模型读到它就会**把已完结的事当成新的遗留问题**去做。
//
// ## 为什么判据是「形状」而不是 kind/score
//
// 与 kernel/rule-shape.ts 同一条纪律: 这类条目的 kind 可能被推断成 context / pattern /
// decision (实测祈使类里 lesson 307 / context 163 / pattern 42 / decision 34), 分数也没有
// 区分度。唯一能把它们认出来的东西是**文本形状本身**  而「这件事做完了」之后形状必然改变
// (用户不会再对它下祈使句), 这正是要的语义。
//
// ## 与 capture/signals.ts 的 DIRECTIVE_PATTERNS 的关系
//
// 那一份判的是「**新**一句话该不该落成约束」; 本文件判的是「**已入库**的正文读起来像不像待办」。
// 词表有重叠但**方向相反**, 且这里多了一维: **完成断言与祈使句的相对位置**  见 looksUnfinished。
//
// 放在 kernel 层: 纯函数、零依赖, 被 L2 的选择方 (trigger) 与门禁脚本共用。

/**
 * 未完成/祈使语气词表。
 *
 * 覆盖面刻意宽: 这是**降级**判据 (命中即不进常驻通道), 而降级的代价只是「从常驻改为按需召回」
 * 与「误把过期待办当常驻」的代价不对称, 所以宁可宽。
 */
const IMPERATIVE_SRC =
  "(你去|你看看|你看下|请你|帮我|给我|继续|还没|尚未|未完成|待办|遗留|记得|别忘了|必须去|赶紧|立刻|下一步要|接下来要|需要补|修复一下|看一下|查一下|处理一下|搞一下|优化一下|现在有[^。\\n]{0,8}bug|想办法)";

/**
 * 完成标记词表 (动词完成态, 不是任何含「完成」的词)。
 *
 * ⚠ 它**不能单独**把一条定为「记录」 判据见 looksUnfinished:
 * 「发布发版完成后…你去给我 review 一下这个PR」同时含完成词与祈使句, 而它是一条
 * **条件式待办** (发版没做完就不该被当成新任务), 必须仍判成未完成。
 */
const DONE_SRC =
  "(已完成|已修好|已修复|修复完成|已解决|已落地|已完成验证|已发版|已提交|已通过|全部完成|已收敛|已关闭|已合并|已上线|已交付|做完了|搞定了|收口)";

/**
 * 词表在 text 里**最后一次**出现的位置 (无命中返回 -1)。
 *
 * ⚠ 实现注意 (踩过): **必须每次现造带 `g` 的正则**  拿一个非全局正则去 `while (exec)` 会
 * 永远返回同一个匹配, 直接死循环 (本文件第一版就是这样挂住的: 一个 import 就再也不返回)。
 * 用 `source` 存词表、用 `new RegExp(src, "g")` 现造, 就把「调用方传什么标志」这件事消掉了。
 */
function lastIndexOf(src: string, text: string): number {
  const re = new RegExp(src, "g");
  let last = -1;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    last = m.index;
    if (m[0].length === 0) re.lastIndex += 1; // 零宽防守 (词表非空, 但别让它有机会死循环)
  }
  return last;
}

/**
 * true = 这条正文读起来像「尚未完成的祈使/待办」⇒ **不进常驻 (always-on) 通道**。
 *
 * 判据 (**顺序敏感**, 这是本函数唯一容易写错的地方): 取「最后一次完成断言」与
 * 「最后一次祈使句」的相对位置 
 *   · 有完成断言, 且它**晚于**任何祈使句 ⇒ 这是**记录**, 放行;
 *   · 否则 (没有完成断言, 或祈使句出现在完成断言**之后**) ⇒ 这是**待办**, 挡掉。
 *
 * 为什么不能「正文里出现完成词就放行」(实测反例, 真库 cb76628b490069077):
 * 「发布发版完成后, 注意必须要完成后全部走通后, 你去给我 review 一下这个PR」含「完成后」,
 * 但它是一句条件式待办; 整段扫完成词会让它拿到常驻资格  而它正是本次要挡掉的那一类。
 *
 * 语义边界 (与调用方约定):
 *   · 本函数**不**判断「它到底完没完成」 那是存储层 resolved 语义位的职责;
 *   · 它只回答「这条**形状上**像不像一条还没办的指令」。形状像 ⇒ 常驻通道不要它,
 *     因为它每轮出现就等于每轮对模型下一次催促。
 *   · 按需召回 (memory_search / 意图通道) **不受影响**  真要复盘那段历史时仍查得到。
 */
export function looksUnfinished(content: string): boolean {
  const text = content.trim();
  if (!text) return false;
  const imperatives = lastIndexOf(IMPERATIVE_SRC, text);
  if (imperatives < 0) return false;
  const done = lastIndexOf(DONE_SRC, text);
  return done < 0 || done < imperatives;
}

/**
 * 常驻通道里给模型看的**状态前缀** (注入行专用, 由 injection-format 拼进正文之前)。
 *
 * 为什么要前缀而不是让模型自己读日期: 实测模型**确实**照记忆做事, 但记忆里没有
 * 「这条已完结」这个信号  它的自述是「记忆里两条直接冲突我的当前动作」(09-30 22:40)。
 * 一句话的状态前缀是零歧义的, 而「日期 + 自行推断」不是。
 */
export const UNFINISHED_TAG = "[待办]";
