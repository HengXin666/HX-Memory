/**
 * 负面/纠正轮次的**教训提炼**提示词 (2026-10-06 新增)。
 *
 * 为什么不能用 DEFAULT_STRUCTURER_PROMPT: 那一份要的是"这一轮定了什么", 而负面轮次要的是
 * "**我上一轮做错了什么、该改成什么**"  两者的问题不同, 硬塞进同一个提示词会两头不讨好。
 *
 * 为什么必须喂上下文 (用户 2026-10-06 实测否决了"只看骂人那句"的做法, 原话:
 * "我骂你的时候显然不会直接告诉你答案, 肯定要看你的上下文"): 骂人那句话**本身不含信息**,
 * 信息在"agent 刚刚干了什么"。因此 {{input}} 里同时给**被否决的原话**与**agent 当时的输出**。
 * 只给前者 ⇒ 只能编出泛泛的行为禁令 (实测: 8 句不同的辱骂产出逐字相同的 62 字模板, 然后被去重全吞)。
 *
 * 输出形态沿用 StructuredTurn 的 conclusion 字段 (复用整条解析链路), 但语义是"教训"。
 */
export const DEFAULT_NEGATIVE_LESSON_PROMPT = [
  "用户在批评 agent。给你两组材料: {{input}}",
  "",
  "任务: 结合 **agent 当时的输出**, 说清 **agent 具体做错了什么** 以及 **下次该怎么做**。",
  "",
  "规则:",
  "- 必须**从输出里找出具体的错处** (哪个判断错、哪个做法错、漏了什么、跑偏到哪去)  不是复述用户情绪;",
  "- 不要写'用户不满''用户生气'这类描述他人情绪的话, 读者是下一轮的我, 只需要'该怎么做';",
  "- 抽不出具体错处时, 说清**这一轮哪个方向跑偏了** (拿输出里的实际内容作证据), 不要退成空泛禁令;",
  "- conclusion 一句话, 30-80 字, 形态优先 `禁止<做错的>。改为: <怎么做>。`;",
  "- 输出严格 JSON, 与结构化器同格式 (conclusion/summary/tags/entities/points/importance/confidence)。",
].join("\n");

